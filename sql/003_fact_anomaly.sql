-- Task 4: AI Anomaly Integration Schema
-- Creates dw.fact_anomaly and dw.v_attendance_anomaly in the PulseIQ analytics warehouse.

CREATE TABLE IF NOT EXISTS dw.fact_anomaly (
    result_id       text PRIMARY KEY,
    source_dataset  text NOT NULL,
    record_id       text NOT NULL,
    employee_id     text NOT NULL,
    period_date     date NOT NULL,
    period_key      integer NOT NULL REFERENCES dw.dim_date (date_key),
    anomaly_score   numeric(6,4) NOT NULL,
    flagged         text NOT NULL,
    reason_code     text NOT NULL,
    reason_text     text NOT NULL,
    money_at_risk   numeric(14,2),
    model_version   text NOT NULL,
    scored_at       timestamp NOT NULL
);

COMMENT ON TABLE dw.fact_anomaly IS 'Grain: one row per anomaly detection result generated by machine learning models.';

CREATE INDEX IF NOT EXISTS ix_fact_anomaly_source_period ON dw.fact_anomaly (source_dataset, period_key);
CREATE INDEX IF NOT EXISTS ix_fact_anomaly_employee      ON dw.fact_anomaly (employee_id);
CREATE INDEX IF NOT EXISTS ix_fact_anomaly_reason        ON dw.fact_anomaly (reason_code);
CREATE INDEX IF NOT EXISTS ix_fact_anomaly_period_key    ON dw.fact_anomaly (period_key);

-- Flat reporting view for attendance anomalies joined with department and employee details
CREATE OR REPLACE VIEW dw.v_attendance_anomaly AS
SELECT 
    a.result_id,
    a.source_dataset,
    a.record_id,
    a.employee_id,
    a.period_date,
    a.period_key,
    a.anomaly_score,
    a.flagged,
    a.reason_code,
    a.reason_text,
    a.model_version,
    a.scored_at,
    d.full_date AS month_end,
    d.year,
    d.month_number,
    d.year_month,
    dep.department_id,
    dep.department_name,
    e.full_name,
    att.scheduled_days,
    att.present_days,
    att.wfh_days,
    att.half_days_unpaid,
    att.paid_leave_days,
    att.unpaid_absence_days,
    att.late_arrivals,
    att.attendance_rate
FROM dw.fact_anomaly a
JOIN dw.dim_date d ON d.date_key = a.period_key
JOIN dw.fact_attendance_monthly att ON att.employee_id = a.employee_id AND att.date_key = a.period_key
JOIN dw.dim_department dep ON dep.department_key = att.department_key
JOIN dw.dim_employee e ON e.employee_key = att.employee_key
WHERE a.source_dataset = 'attendance_monthly_features';

-- Grant SELECT to superset_ro
GRANT SELECT ON dw.fact_anomaly TO superset_ro;
GRANT SELECT ON dw.v_attendance_anomaly TO superset_ro;
